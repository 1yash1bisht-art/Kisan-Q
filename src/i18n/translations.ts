// Safe translation getter with Hindi and English fallback for absolute resilience
export const getTranslation = (lang: Language): Record<string, string> => {
  const targetDict = TRANSLATIONS[lang] || TRANSLATIONS['hi'];
  return new Proxy(targetDict, {
    get: (target, prop: string) => {
      if (prop in target && target[prop]) return target[prop];
      if (TRANSLATIONS['hi'] && prop in TRANSLATIONS['hi'] && TRANSLATIONS['hi'][prop]) {
        return TRANSLATIONS['hi'][prop];
      }
      if (TRANSLATIONS['en'] && prop in TRANSLATIONS['en'] && TRANSLATIONS['en'][prop]) {
        return TRANSLATIONS['en'][prop];
      }
      return prop;
    }
  });
};
